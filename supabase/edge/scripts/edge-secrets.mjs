// Builds supabase/.env.edge — the secrets file for the `api` Edge Function —
// from backend/.env, then prints the command that uploads it.
//
//   node scripts/edge-secrets.mjs [--cors https://app.example] [--keep-dev-env]
//   npx supabase secrets set --env-file supabase/.env.edge --project-ref <ref>
//
// What carries over, and why:
//
//  - The auth keyring (JWT_*, OTP_PEPPER, GUEST_TOKEN_PEPPER, OTP_DELIVERY_KEY,
//    TOTP_ENC_KEY) is copied verbatim. The migrated rows were written with
//    these keys: TOTP secrets are encrypted with TOTP_ENC_KEY, sealed OTPs with
//    OTP_DELIVERY_KEY. New keys would lock every enrolled authenticator out.
//  - Provider credentials (WhatsApp, SMS, voice, delivery carriers, AI) and
//    tuning variables are copied when they have a value.
//
// What does not, and why:
//
//  - DATABASE_URL, HOST, PORT, API_PREFIX, TRUST_PROXY, MEDIA_*: the function
//    derives them from Supabase (see supabase/edge/src/runtime/env.ts).
//  - OTP_DEV_ECHO, OTP_DEV_INBOX_ENABLED, PAYMENTS_SANDBOX_CONFIRMATION: the
//    backend refuses to start in production with any of them on.
//  - Anything named SUPABASE_*: reserved by Supabase and injected already.
//
// Added: NODE_ENV=production, a fresh REEM_CRON_SECRET (also to be stored in
// Vault — the command is printed), and CORS_ORIGINS.
//
// The output file holds live secrets. It is git-ignored; delete it after
// uploading.
import { randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../..');
const args = process.argv.slice(2);
const flag = (name) => {
  const index = args.indexOf(`--${name}`);
  return index === -1 ? undefined : args[index + 1];
};

const DERIVED = new Set([
  'DATABASE_URL', 'HOST', 'PORT', 'API_PREFIX', 'TRUST_PROXY',
  'MEDIA_DRIVER', 'MEDIA_LOCAL_ROOT', 'MEDIA_PUBLIC_BASE_URL', 'MEDIA_PUBLIC_ORIGIN',
  'WS_QUERY_TOKEN_UNTIL', 'NODE_ENV', 'CORS_ORIGINS',
]);
const DEV_ONLY = new Set(['OTP_DEV_ECHO', 'OTP_DEV_INBOX_ENABLED', 'PAYMENTS_SANDBOX_CONFIRMATION']);
const REQUIRED = ['JWT_ACCESS_SECRET', 'JWT_REFRESH_SECRET', 'OTP_PEPPER', 'GUEST_TOKEN_PEPPER', 'OTP_DELIVERY_KEY', 'TOTP_ENC_KEY'];

function parseEnv(text) {
  const values = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

const source = parseEnv(readFileSync(path.join(repo, 'backend', '.env'), 'utf8'));
const missing = REQUIRED.filter((key) => !source[key]);
if (missing.length) {
  console.error(`backend/.env lacks ${missing.join(', ')} — the migrated data cannot be read without them.`);
  process.exit(1);
}

const out = {};
const dropped = [];
for (const [key, value] of Object.entries(source)) {
  if (key.startsWith('SUPABASE_')) continue;
  if (DERIVED.has(key)) continue;
  if (DEV_ONLY.has(key) && !args.includes('--keep-dev-env')) {
    if (value === 'true') dropped.push(key);
    continue;
  }
  if (value === '') continue;
  out[key] = value;
}

out.NODE_ENV = args.includes('--keep-dev-env') ? 'development' : 'production';
out.CORS_ORIGINS = flag('cors') ?? 'https://reem.invalid';
out.REEM_CRON_SECRET = randomBytes(32).toString('base64url');
out.REEM_BOOT_METRICS = 'true';

const file = path.join(repo, 'supabase', '.env.edge');
const body = [
  '# Secrets for the Supabase Edge Function `api`. Generated by supabase/edge/scripts/edge-secrets.mjs.',
  '# LIVE SECRETS — never commit; delete after `supabase secrets set --env-file`.',
  ...Object.entries(out).map(([key, value]) => `${key}=${JSON.stringify(value)}`),
  '',
].join('\n');
writeFileSync(file, body, { mode: 0o600 });

console.log(`Wrote ${Object.keys(out).length} secrets to ${path.relative(repo, file)}`);
if (dropped.length) console.log(`Left out development-only switches: ${dropped.join(', ')}`);
if (!flag('cors')) {
  console.log('CORS_ORIGINS is a placeholder: mobile apps do not need CORS; pass --cors <origin> for a web build.');
}
console.log(`
Next:
  npx supabase secrets set --env-file supabase/.env.edge --project-ref <project-ref>

and store the same cron secret in Vault (SQL editor):
  select vault.create_secret('${out.REEM_CRON_SECRET}', 'reem_cron_secret');
  select vault.create_secret('https://<project-ref>.supabase.co/functions/v1/api', 'reem_api_url');`);
